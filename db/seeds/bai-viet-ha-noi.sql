## Phở Hà Nội ăn thế nào cho đúng?

Ăn phở vào buổi sáng, chọn quán có nồi nước dùng đang sôi. Tháng 12/2024, Bộ Văn hóa, Thể thao và Du lịch ghi danh *Tri thức dân gian Phở Hà Nội* là di sản văn hóa phi vật thể quốc gia.

- **Phở bò:** gọi tái, chín, tái lăn hoặc nạm, gầu tùy khẩu vị. Phở tái lăn là thịt xào sơ trên chảo trước khi chan nước.
- **Phở gà:** nước trong và nhẹ hơn, thường ăn kèm lá chanh thái chỉ.
- **Gia vị:** quán phở Hà Nội thường để sẵn chanh, ớt, tỏi ngâm giấm. Nếm nước dùng trước rồi hãy thêm.

Không cần tìm đúng một quán nổi tiếng. Quán đông khách địa phương lúc 7–8 giờ sáng thường là quán tốt.

## Bún chả, bún thang, bánh cuốn: khác nhau ở đâu?

Bún chả là món trưa. Bún thang và bánh cuốn hợp bữa sáng.

- **Bún chả:** chả viên và chả miếng nướng than, ngâm trong bát nước chấm chua ngọt, ăn với bún và rau sống. Quán Bún chả Hương Liên ở 24 Lê Văn Hưu được biết đến rộng rãi sau khi Tổng thống Mỹ Barack Obama và đầu bếp Anthony Bourdain ăn tại đây năm 2016.
- **Bún thang:** bún chan nước dùng gà, phủ trứng tráng, giò lụa, thịt gà xé sợi, thêm chút mắm tôm. Món cầu kỳ, thường chỉ có ở quán chuyên.
- **Bánh cuốn:** bánh tráng mỏng, nhân thịt và mộc nhĩ, chấm nước mắm pha. Bánh cuốn Thanh Trì là loại không nhân, mỏng, ăn với chả.
- **Bún đậu mắm tôm:** đậu rán, chả cốm, thịt luộc, chấm mắm tôm đánh chanh. Nếu không ăn được mắm tôm, gọi nước mắm thay thế.

