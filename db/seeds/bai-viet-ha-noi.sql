## Chùa Thầy có gì để xem?

Chùa Thầy (còn gọi là chùa Cả) nằm dưới chân núi Sài Sơn, gắn với Thiền sư Từ Đạo Hạnh. Phần dưới đi bộ trên mặt phẳng, phần trên núi phải leo dốc.

- **Hồ Long Trì và thủy đình:** thủy đình giữa hồ là sân khấu múa rối nước vào mùa lễ hội.
- **Cầu Nhật Tiên và cầu Nguyệt Tiên:** hai cây cầu có mái nối bờ hồ với khu chùa.
- **Ba tòa chùa Hạ, Trung, Thượng:** chùa Thượng thờ tượng Thiền sư Từ Đạo Hạnh.
- **Chùa Cao và hang Cắc Cớ:** đi theo đường núi phía sau chùa. Hang Cắc Cớ có nhiều tầng, khách thường chỉ vào tầng đầu.

Đường núi lát đá, dễ trơn khi trời mưa. Mang giày đế bám, đừng đi dép cao gót.

## Chùa Tây Phương có gì đặc biệt?

Điểm đáng xem nhất ở Tây Phương là tượng. Chùa có hơn 70 pho tượng, chủ yếu bằng gỗ mít sơn son thếp vàng. Bộ tượng Phật giáo thời Tây Sơn (cuối thế kỷ 18) được công nhận là Bảo vật quốc gia năm 2015. Chùa được xếp hạng Di tích quốc gia đặc biệt năm 2014.

- **Đường lên chùa:** chùa nằm trên ngọn núi cao hơn 100 m. Bạn leo khoảng 240 bậc đá ong (các nguồn ghi 237–239 bậc). Đường có cây che, nhưng vẫn mệt vào trưa hè.
- **Kiến trúc:** ba tòa Hạ, Trung, Thượng, mái chồng diêm nhiều tầng, đầu đao cong.
- **Tượng La Hán:** 18 vị La Hán ở chùa Thượng, mỗi pho một dáng vẻ, nét mặt khác nhau.

Bên trong điện khá tối. Đứng lâu một chút cho mắt quen rồi hãy xem kỹ từng pho tượng.

