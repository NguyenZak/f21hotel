## Bảo tàng có những khu nào?

Có ba khu chính: Tòa Trống đồng, Vườn Kiến trúc và Tòa Cánh diều. Bảo tàng khai trương ngày 12/11/1997, khuôn viên rộng gần 4,4 ha.

### Tòa Trống đồng

Giới thiệu 54 dân tộc Việt Nam. Phần trưng bày thường xuyên rộng khoảng 2.000m² với hơn 1.600 hiện vật: trang phục, công cụ, đồ nghi lễ, mô hình sinh hoạt. Nên xem khu này trước để có bức tranh chung.

### Vườn Kiến trúc

Khu ngoài trời rộng khoảng 20.000m², dựng lại 10 công trình kiến trúc dân gian của nhiều dân tộc và vùng văn hóa, trong đó có nhà dài Ê Đê và nhà rông Tây Nguyên. Bạn được leo lên, đi vào bên trong nhiều ngôi nhà. Phần này hợp với trẻ em vì có chỗ đi lại, khám phá.

### Tòa Cánh diều

Trưng bày về văn hóa các tộc người Đông Nam Á, kết nối với phần Việt Nam ở Tòa Trống đồng. Nếu thời gian ít, có thể bỏ khu này.

