| Mùa | Thứ Ba – thứ Năm | Thứ Bảy, Chủ nhật, ngày lễ |
|---|---|---|
| Mùa nóng (1/4 – 31/10) | 7:30 – 10:30 | 7:30 – 11:00 |
| Mùa lạnh (1/11 – 31/3) | 8:00 – 11:00 | 8:00 – 11:30 |

- Nếu ngày 19/5, 2/9 hoặc mùng 1 Tết rơi vào thứ Hai hay thứ Sáu, Lăng vẫn mở.
- Lăng đóng khoảng hai tháng mỗi năm để tu bổ định kỳ. Năm 2026, Lăng ngừng đón khách từ 4/9 đến 2/11 và mở lại từ 3/11.
- Giờ trên là giờ Lăng nhận khách. Đến sát giờ đóng có thể không kịp vào.

## Vào Lăng có mất vé không, xếp hàng ở đâu?

Không mất vé, không cần đặt trước. Ai đến trước vào trước.

- Khách lẻ và đoàn tập kết ở số 17 phố Ngọc Hà, qua cổng an ninh rồi xếp hàng đi vào Lăng.
- Đoàn có vòng hoa hoặc đăng ký xem phim tư liệu tập kết ở số 8 Hùng Vương.
- Ba lô, túi xách lớn phải gửi ở quầy giữ đồ trước cổng an ninh.
- Ngày cuối tuần, ngày lễ, hè, hàng có thể dài 30–90 phút. Đến trước giờ mở cửa 30–45 phút là hợp lý.

## Mặc gì và cần lưu ý gì?

Mặc kín vai và đầu gối. Người mặc quần soóc, áo hai dây, váy ngắn sẽ không được vào, và ở đó không có đồ cho mượn.

- Bỏ mũ, kính râm khi vào trong.
- Không chụp ảnh, quay phim bên trong Lăng.
- Không mang đồ ăn, đồ uống, không hút thuốc.
- Đi thành hàng, giữ trật tự, không dừng lại lâu trong phòng thi hài.
- Đưa trẻ nhỏ đi thì dặn trước để bé giữ im lặng. Quy định độ tuổi tối thiểu của trẻ [CẦN XÁC NHẬN].

## Quảng trường Ba Đình: lễ thượng cờ, hạ cờ

Quảng trường mở tự do, không mất vé. Lễ thượng cờ và hạ cờ diễn ra hằng ngày.

- **Thượng cờ**: 6:00 vào mùa nóng (1/4 – 31/10), 6:30 vào mùa lạnh (1/11 – 31/3).
- **Hạ cờ**: 21:00 hằng ngày.
- Muốn đứng gần, đến trước 15–20 phút. Dịp lễ lớn như 2/9 rất đông.

